#!/usr/bin/env node

import fs from 'fs';
import path from 'path';
import crypto from 'crypto';
import readline from 'readline';

import { browserHistoryImporter } from '../src/utils/browser-importer.js';
import { localStore } from '../src/utils/local-store.js';

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout
});

const question = (query) => new Promise((resolve) => rl.question(query, resolve));

async function runBrowserImport() {
  console.log('\n================================================================');
  console.log('📥 Zalo-Flow Browser History Importer (IndexedDB to SQLite)');
  console.log('================================================================\n');

  console.log('🔍 Scanning for Zalo Web browser profiles...');
  const profiles = browserHistoryImporter.detectProfiles();

  if (profiles.length === 0) {
    console.log('❌ No Zalo Web profiles found on this computer.');
    console.log('Ensure you have logged into https://chat.zalo.me on Chrome/Edge/CocCoc/Brave.');
    rl.close();
    return;
  }

  console.log(`\nFound ${profiles.length} Zalo Web profile(s):`);
  profiles.forEach((p, idx) => {
    console.log(` [${idx + 1}] ${p.browser} - ${p.profile} (${p.sizeFormatted}, updated: ${new Date(p.mtime).toLocaleString()})`);
  });

  const choiceStr = (await question(`\nSelect profile to import [1-${profiles.length}] (default: 1): `)) || '1';
  const choiceIdx = Math.max(0, Math.min(profiles.length - 1, parseInt(choiceStr, 10) - 1));
  const selectedProfile = profiles[choiceIdx];

  console.log(`\n⏳ Importing from: ${selectedProfile.browser} (${selectedProfile.profile})...`);
  try {
    const result = await browserHistoryImporter.importProfile(selectedProfile.path, localStore);
    console.log('\n================================================================');
    console.log('🎉 Migration Completed Successfully!');
    console.log(` - Conversations Imported: ${result.conversationsCount}`);
    console.log(` - Messages Imported:      ${result.messagesCount}`);
    console.log(` - Time Taken:            ${result.durationMs}ms`);
    console.log('================================================================\n');
  } catch (err) {
    console.error('❌ Migration failed:', err.message);
  }
  rl.close();
}

async function runSetupWizard() {
  console.log('\n================================================================');
  console.log('⚡ Welcome to Zalo-Flow Quick Setup Wizard!');
  console.log('================================================================\n');

  const envPath = path.resolve(process.cwd(), '.env');
  if (fs.existsSync(envPath)) {
    const overwrite = await question('⚠️  A .env file already exists. Overwrite? (y/N): ');
    if (overwrite.toLowerCase() !== 'y') {
      console.log('Setup aborted.');
      rl.close();
      return;
    }
  }

  console.log('\n📌 [Step 1/4] Server & Security Settings');
  const port = (await question('Enter Server Port (default: 3000): ')) || '3000';
  const autoSecret = crypto.randomBytes(16).toString('hex');
  const sessionSecret = (await question(`Enter Session Passphrase (default: auto-generated ${autoSecret}): `)) || autoSecret;

  console.log('\n📌 [Step 2/4] Chatwoot CRM Integration (Optional)');
  const chatwootUrl = await question('Chatwoot API URL (e.g. https://app.chatwoot.com, leave empty to skip): ');
  let chatwootToken = '';
  let chatwootAccountId = '';
  let chatwootInboxId = '';

  if (chatwootUrl.trim()) {
    chatwootToken = await question('Chatwoot User API Access Token: ');
    chatwootAccountId = await question('Chatwoot Account ID: ');
    chatwootInboxId = await question('Chatwoot API Channel Inbox ID: ');
  }

  console.log('\n📌 [Step 3/4] AI Engine Setup (Optional)');
  const aiProvider = (await question('AI Provider (gemini / deepseek / openai / ollama / none, default: gemini): ')) || 'gemini';
  let aiApiKey = '';
  let aiModel = 'gemini-2.5-flash';
  if (aiProvider !== 'none' && aiProvider !== 'ollama') {
    aiApiKey = await question(`Enter API Key for ${aiProvider} (leave empty to configure in Web UI): `);
    if (aiProvider === 'deepseek') aiModel = 'deepseek-chat';
    else if (aiProvider === 'openai') aiModel = 'gpt-4o-mini';
  }

  console.log('\n📌 [Step 4/4] Generating .env configuration...');

  const envContent = `# Auto-generated by Zalo-Flow Setup Wizard on ${new Date().toISOString()}

PORT=${port}
HOST=0.0.0.0
SESSION_SECRET=${sessionSecret}
ADMIN_API_TOKEN=

# Chatwoot CRM Adapter
CHATWOOT_API_URL=${chatwootUrl.trim()}
CHATWOOT_API_TOKEN=${chatwootToken.trim()}
CHATWOOT_ACCOUNT_ID=${chatwootAccountId.trim()}
CHATWOOT_INBOX_ID=${chatwootInboxId.trim()}

# Anti-Ban Safety Guardrails
RATE_LIMIT_PER_SECOND=0.33
RATE_LIMIT_PER_MINUTE=20
FLOOD_THRESHOLD=5
FLOOD_MUTE_SECONDS=60
SELF_ECHO_TTL_SECONDS=30

# AI Engine & Auto-Reply
AI_PROVIDER=${aiProvider.trim()}
AI_API_KEY=${aiApiKey.trim()}
AI_MODEL=${aiModel}
AI_FALLBACK_API_KEY=
OLLAMA_BASE_URL=http://localhost:11434
`;

  fs.writeFileSync(envPath, envContent, 'utf-8');
  console.log('\n✅ Successfully generated .env file!');
  console.log('👉 Next step: Run "npm start" or "npm run dev" to launch Zalo-Flow.\n');
  rl.close();
}

async function main() {
  const arg = process.argv[2];
  if (arg === 'import-browser' || arg === 'import:browser' || arg === 'import') {
    await runBrowserImport();
  } else {
    await runSetupWizard();
  }
}

main().catch((err) => {
  console.error('❌ CLI error:', err);
  rl.close();
});
